export type UiKey = keyof (typeof ui)[typeof DEFAULT_LOCALE];

/**
 * Übersetzer für eine Sprache. Fehlt ein Schlüssel, fällt er auf Deutsch zurück,
 * damit eine unfertige Übersetzung nie eine leere Seite erzeugt.
 *
 *   const _ = useTranslations(lang);
 *   _('nav.shop')
 *   _('cfg.minorder.short', { amount: '12 €' })
 */
export function useTranslations(locale: Locale) {
  return function translate(key: UiKey, vars?: Record<string, string | number>): string {
    const dict = ui[locale] as Record<string, string>;
    const fallback = ui[DEFAULT_LOCALE] as Record<string, string>;
    let value = dict[key] ?? fallback[key] ?? key;
    if (vars) {
      for (const [name, replacement] of Object.entries(vars)) {
        value = value.replaceAll(`{${name}}`, String(replacement));
      }
    }
    return value;
  };
}
